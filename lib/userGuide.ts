/**
 * The user guide: a written PDF served from public/, and a video hosted on
 * Cloudflare Stream.
 *
 * Everything that needs to change when the guide is replaced lives in this
 * file. Both halves are independent and both are optional — whichever is left
 * blank simply does not appear in the footer, so a half-finished setup can
 * never ship a dead link to production.
 */

/**
 * The Stream "Customer subdomain", copied whole from the Cloudflare dashboard:
 * Images & Stream -> Hosted videos -> Account details panel on the right.
 * It already includes the "customer-" prefix, e.g. customer-esndw3dpth4a1b2c3.
 */
export const STREAM_CUSTOMER_SUBDOMAIN = 'customer-esndw3dpthbsv619.cloudflarestream.com'

/**
 * The video's UID — open the video in the Stream dashboard and copy the long
 * hex string from the address bar or the Settings panel. 32 hex characters.
 */
export const STREAM_VIDEO_UID = 'f5cd7c8e9fe6202e705ab388f9d98233'

/**
 * The written guide, as a path relative to public/. Fill this in only once the
 * file is actually sitting there, or the footer will link to a 404.
 * Putting public/docs/user-guide.pdf in place means: '/docs/user-guide.pdf'
 */
export const GUIDE_PDF_PATH = ''

/** Letterbox bars inside the player, matched to the footer navy. */
const PLAYER_BACKGROUND = '#122f51'

export const hasGuideVideo = Boolean(STREAM_CUSTOMER_SUBDOMAIN && STREAM_VIDEO_UID)
export const hasGuideDocument = Boolean(GUIDE_PDF_PATH)

/** The still frame shown before playback starts. Generated by Cloudflare. */
export function streamPosterUrl(atSeconds = 2): string {
  if (!hasGuideVideo) return ''
  return (
    `https://${STREAM_CUSTOMER_SUBDOMAIN}.cloudflarestream.com` +
    `/${STREAM_VIDEO_UID}/thumbnails/thumbnail.jpg?time=${atSeconds}s&height=720`
  )
}

/**
 * The player URL. Cloudflare's own iframe player is used rather than a raw
 * HLS manifest: it carries no Cloudflare branding, picks the bitrate to suit
 * the viewer's connection, and plays natively on iOS Safari, which an
 * hls.js-based player does not do without extra work.
 */
export function streamIframeSrc(): string {
  if (!hasGuideVideo) return ''
  const params = new URLSearchParams({
    poster: streamPosterUrl(),
    letterboxColor: PLAYER_BACKGROUND,
    preload: 'metadata',
  })
  return (
    `https://${STREAM_CUSTOMER_SUBDOMAIN}.cloudflarestream.com` +
    `/${STREAM_VIDEO_UID}/iframe?${params.toString()}`
  )
}
